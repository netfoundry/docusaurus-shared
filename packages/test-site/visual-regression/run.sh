#!/usr/bin/env bash
# Visual-regression check for the docusaurus-shared test-site.
#
# The single entry point for local runs and CI. It builds the theme and the test-site, serves the static output, and
# runs the Playwright screenshot comparison against the pages in pages.ts.
#
# Baselines are NOT committed. They live as a tarball attached to a GitHub release (rolling tag, default
# "test-site-vrt-baselines"). Pull them down to verify, push them up after an intentional change.
#
# Baseline parity: Playwright screenshots are OS-specific. The published baselines are the Linux ones, produced inside
# the pinned Playwright container (--docker). Verify with --docker too so the comparison runs on the same platform. A
# native run on Windows/macOS is only for eyeballing; it writes OS-suffixed snapshots that are never published.
#
# Usage:
#   ./run.sh --docker --pull-baselines               # verify against published baselines (the common case)
#   ./run.sh --docker --update --publish-baselines   # regenerate baselines and publish them
#   ./run.sh --docker --update                       # regenerate locally without publishing (inspect first)
#   ./run.sh --base-url URL --pull-baselines         # verify an already-running site (skips build + serve)
#   ./run.sh --skip-build                            # reuse an existing packages/test-site/build
#   ./run.sh --port 5000                             # static server port (default 4173)
#   ./run.sh --baselines-tag TAG                     # release tag holding the baselines (default test-site-vrt-baselines)
#   ./run.sh --repo OWNER/REPO                       # target repo for gh (default: inferred from git remote)
#   ./run.sh --mount-path PATH                       # bind-mount source for --docker (default: repo root)
#   ./run.sh --container-cli wslc.exe                # container CLI for --docker (default: docker)
#   ./run.sh --accept-visual-changes                 # skip comparison + pass (intentional change; CI label)
#   ./run.sh --run-url URL                           # CI run URL, used in the failure hint
#   ./run.sh --summary-file PATH                     # also write the failure hint here (CI step summary)
set -euo pipefail

VR_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SITE_DIR="$(cd "$VR_DIR/.." && pwd)"
REPO_ROOT="$(cd "$SITE_DIR/../.." && pwd)"

UPDATE=0
USE_DOCKER=0
SKIP_BUILD=0
PULL_BASELINES=0
PUBLISH_BASELINES=0
PORT=4173
BASE_URL=""
BASELINES_TAG="test-site-vrt-baselines"
GH_REPO=""
MOUNT_PATH=""
CONTAINER_CLI="docker"
ACCEPT_CHANGES=0
RUN_URL=""
SUMMARY_FILE=""
IN_CONTAINER=0

while [[ $# -gt 0 ]]; do
  case "$1" in
    --update) UPDATE=1; shift ;;
    --docker) USE_DOCKER=1; shift ;;
    --skip-build) SKIP_BUILD=1; shift ;;
    --pull-baselines) PULL_BASELINES=1; shift ;;
    --publish-baselines) PUBLISH_BASELINES=1; shift ;;
    --port) PORT="$2"; shift 2 ;;
    --base-url) BASE_URL="$2"; shift 2 ;;
    --baselines-tag) BASELINES_TAG="$2"; shift 2 ;;
    --repo) GH_REPO="$2"; shift 2 ;;
    --mount-path) MOUNT_PATH="$2"; shift 2 ;;
    --container-cli) CONTAINER_CLI="$2"; shift 2 ;;
    --accept-visual-changes) ACCEPT_CHANGES=1; shift ;;
    --run-url) RUN_URL="$2"; shift 2 ;;
    --summary-file) SUMMARY_FILE="$2"; shift 2 ;;
    # Internal: set by the --docker path. The host prints the failure hint, so the inner run stays quiet about it.
    --in-container) IN_CONTAINER=1; shift ;;
    -h|--help) sed -n '2,27p' "$0"; exit 0 ;;
    *) echo "Unknown argument: $1" >&2; exit 2 ;;
  esac
done

GH_REPO_FLAG=()
[[ -n "$GH_REPO" ]] && GH_REPO_FLAG=(--repo "$GH_REPO")
SNAPSHOTS_DIR="$VR_DIR/snapshots"
# Written by the in-container run when Playwright fails, so the host can tell a screenshot diff from an infra failure.
PW_FAILED_MARKER="$VR_DIR/test-results/.playwright-failed"

# Intentional visual change accepted (the PR label): pass without comparing. The publish job regenerates the
# baselines after merge to main.
if [[ "$ACCEPT_CHANGES" == "1" ]]; then
  echo ">> --accept-visual-changes set: skipping visual comparison (baselines will be"
  echo ">> regenerated by the publish job after merge to main)."
  exit 0
fi

# Printed when the comparison fails: how to accept the change and how to see the diffs.
failure_hint() {
  local where="the workflow run"
  [[ -n "$RUN_URL" ]] && where="$RUN_URL"
  local hint
  hint=$(cat <<EOF
### Test-site visual regression failed

Some test-site pages no longer match the published baseline screenshots.

**If the change is intentional**, add the \`visual-baseline-update\` label to the pull request. The check then passes,
and the baselines republish when the pull request merges to \`main\`.

**To see the diffs:**

1. Open $where and download the \`test-site-visual-regression-report\` artifact.
2. Unzip it and open \`playwright-report/index.html\` in a browser.
3. Click a failed test. Each one shows the expected, actual, and diff images, with a slider to compare them.

To reproduce locally (Linux or WSL with Docker):

\`\`\`bash
packages/test-site/visual-regression/run.sh --docker --pull-baselines
npx --prefix packages/test-site/visual-regression playwright show-report packages/test-site/visual-regression/playwright-report
\`\`\`
EOF
)
  echo
  echo "$hint"
  echo
  # Annotation on the run page, so the hint shows without opening the log.
  echo "::error title=Test-site visual regression::Screenshots differ from the baselines. If intended, add the" \
    "'visual-baseline-update' label to the PR. To see the diffs, download the test-site-visual-regression-report" \
    "artifact and open playwright-report/index.html."
  [[ -n "$SUMMARY_FILE" ]] && echo "$hint" >> "$SUMMARY_FILE"
  return 0
}

# --- Baseline storage (GitHub release asset, via gh) --------------------------------------------------------------
# These run on the HOST, never inside the Playwright container (which has no gh). The container shares the repo via a
# bind mount, so baselines pulled here are visible to the in-container run, and snapshots written there are visible
# here for publish.

pull_baselines() {
  echo ">> Pulling baselines from release '$BASELINES_TAG'"
  command -v gh >/dev/null || { echo "ERROR: gh (GitHub CLI) is required for --pull-baselines." >&2; exit 1; }

  # Soft-skip bootstrap: with no release or no baselines.tgz there is nothing to compare against, so pass with a note.
  # Any other gh failure (auth, network) is a hard error. The first merge to main publishes the first set.
  local err
  if ! err="$(gh release view "$BASELINES_TAG" "${GH_REPO_FLAG[@]}" 2>&1 >/dev/null)"; then
    if echo "$err" | grep -qi "not found\|release not found\|no release"; then
      echo ">> No '$BASELINES_TAG' release yet; skipping verification (soft pass)."
      echo ">> Merge to main (or run the publish job) to create the first baselines."
      exit 0
    fi
    echo "ERROR: gh release view failed: $err" >&2; exit 1
  fi

  local tmp; tmp="$(mktemp -d)"
  if ! err="$(gh release download "$BASELINES_TAG" "${GH_REPO_FLAG[@]}" --pattern baselines.tgz --dir "$tmp" 2>&1)"; then
    if echo "$err" | grep -qi "no assets\|asset not found\|not found\|no such"; then
      echo ">> Release '$BASELINES_TAG' has no baselines.tgz yet; skipping verification (soft pass)."
      rm -rf "$tmp"; exit 0
    fi
    echo "ERROR: could not download baselines.tgz: $err" >&2
    rm -rf "$tmp"; exit 1
  fi
  rm -rf "$SNAPSHOTS_DIR"
  tar -xzf "$tmp/baselines.tgz" -C "$VR_DIR"
  rm -rf "$tmp"
  echo ">> Baselines restored to $SNAPSHOTS_DIR"
}

publish_baselines() {
  echo ">> Publishing baselines to release '$BASELINES_TAG'"
  command -v gh >/dev/null || { echo "ERROR: gh (GitHub CLI) is required for --publish-baselines." >&2; exit 1; }
  [[ -d "$SNAPSHOTS_DIR" ]] || { echo "ERROR: no snapshots/ to publish. Run with --update first." >&2; exit 1; }
  local tarball="$VR_DIR/baselines.tgz"
  tar -czf "$tarball" -C "$VR_DIR" snapshots
  if ! gh release view "$BASELINES_TAG" "${GH_REPO_FLAG[@]}" >/dev/null 2>&1; then
    gh release create "$BASELINES_TAG" "${GH_REPO_FLAG[@]}" \
      --title "Test-site visual-regression baselines" \
      --notes "Baseline screenshots for the test-site visual-regression check. Managed by packages/test-site/visual-regression/run.sh; this is not a software release." \
      --prerelease
  fi
  gh release upload "$BASELINES_TAG" "$tarball" "${GH_REPO_FLAG[@]}" --clobber
  rm -f "$tarball"
  echo ">> Baselines published"
}

# The pinned Playwright image follows the dependency version so the container's browsers match @playwright/test.
PW_VERSION="$(grep -oE '"@playwright/test":[[:space:]]*"[0-9.]+"' "$VR_DIR/package.json" | grep -oE '[0-9]+\.[0-9]+\.[0-9]+')"

# --- Docker mode: gh work on the host, build+serve+test in the container -----------------------------------------
if [[ "$USE_DOCKER" == "1" ]]; then
  [[ "$PULL_BASELINES" == "1" ]] && pull_baselines
  IMAGE="mcr.microsoft.com/playwright:v${PW_VERSION}-noble"
  echo ">> Running build/serve/test inside $IMAGE for Linux baseline parity"
  inner=(--in-container)
  [[ "$UPDATE" == "1" ]] && inner+=(--update)
  [[ "$SKIP_BUILD" == "1" ]] && inner+=(--skip-build)
  inner+=(--port "$PORT")
  [[ -n "$BASE_URL" ]] && inner+=(--base-url "$BASE_URL")
  # Defaults to the repo root, which is right on Linux, WSL, and CI. Pass --mount-path if your Docker daemon needs a
  # different host path form.
  host_mount="${MOUNT_PATH:-$REPO_ROOT}"
  # No -t: this must run in non-tty contexts (background shells, CI). corepack provisions the repo's pinned yarn.
  rm -f "$PW_FAILED_MARKER"
  rc=0
  # MSYS_NO_PATHCONV stops Git Bash rewriting /work into a Windows path when the CLI is a Windows exe (wslc.exe).
  MSYS_NO_PATHCONV=1 "$CONTAINER_CLI" run --rm \
    -v "${host_mount}:/work" -w /work \
    -e CI="${CI:-}" \
    "$IMAGE" \
    bash -lc "corepack enable && /work/packages/test-site/visual-regression/run.sh ${inner[*]}" || rc=$?
  if [[ "$rc" != "0" ]]; then
    # Only a Playwright failure means the screenshots differ. A failed mount, build, or server start does not.
    if [[ -f "$PW_FAILED_MARKER" ]]; then
      [[ "$UPDATE" != "1" ]] && failure_hint
    else
      echo "ERROR: the container run failed (exit $rc) before Playwright compared any screenshots." >&2
      [[ -z "$MOUNT_PATH" ]] && echo "If the container cannot see the repo, pass --mount-path with a host path" \
        "your container CLI understands (for wslc.exe: D:/path/to/repo)." >&2
    fi
    exit "$rc"
  fi
  [[ "$PUBLISH_BASELINES" == "1" ]] && publish_baselines
  exit 0
fi

cleanup() {
  if [[ -n "${SERVER_PID:-}" ]] && kill -0 "$SERVER_PID" 2>/dev/null; then
    echo ">> Stopping static server (pid $SERVER_PID)"
    kill "$SERVER_PID" 2>/dev/null || true
    wait "$SERVER_PID" 2>/dev/null || true
  fi
}
trap cleanup EXIT

install_vr_deps() {
  echo ">> Installing visual-regression dependencies"
  ( cd "$VR_DIR" && npm install --no-audit --no-fund --silent )
  # In the Playwright image the matching browser is preinstalled; elsewhere this fetches it.
  ( cd "$VR_DIR" && npx playwright install chromium >/dev/null )
}

run_playwright() {
  local args=(test)
  [[ "$UPDATE" == "1" ]] && args+=(--update-snapshots)
  echo ">> Running Playwright (${args[*]})"
  local rc=0
  ( cd "$VR_DIR" && npx playwright "${args[@]}" ) || rc=$?
  if [[ "$rc" != "0" ]]; then
    [[ "$IN_CONTAINER" == "1" ]] && mkdir -p "$(dirname "$PW_FAILED_MARKER")" && touch "$PW_FAILED_MARKER"
    [[ "$UPDATE" != "1" && "$IN_CONTAINER" != "1" ]] && failure_hint
    exit "$rc"
  fi
}

# In the non-docker (native / base-url) path, gh runs here directly.
[[ "$PULL_BASELINES" == "1" ]] && pull_baselines

# Mode A: site already running somewhere. Point the tests at it.
if [[ -n "$BASE_URL" ]]; then
  export VRT_BASE_URL="$BASE_URL"
  echo ">> Testing already-running site at $BASE_URL"
  install_vr_deps
  run_playwright
  [[ "$PUBLISH_BASELINES" == "1" ]] && publish_baselines
  echo ">> Done. HTML report: $VR_DIR/playwright-report/index.html"
  exit 0
fi

# Mode B: build + serve locally.
if [[ "$SKIP_BUILD" != "1" ]]; then
  echo ">> Installing workspace dependencies"
  ( cd "$REPO_ROOT" && yarn install --frozen-lockfile )
  echo ">> Building the theme"
  ( cd "$REPO_ROOT" && yarn theme:build )
  echo ">> Building the test-site"
  ( cd "$REPO_ROOT" && yarn test-site:build )
fi

if [[ ! -d "$SITE_DIR/build" ]]; then
  echo "ERROR: $SITE_DIR/build does not exist. Run without --skip-build first." >&2
  exit 1
fi

export VRT_BASE_URL="http://127.0.0.1:${PORT}"
echo ">> Serving built site on $VRT_BASE_URL"
( cd "$SITE_DIR" && yarn serve --port "$PORT" --host 127.0.0.1 --no-open ) &
SERVER_PID=$!

echo ">> Waiting for server to respond"
for i in $(seq 1 60); do
  if curl -fsS "$VRT_BASE_URL/" -o /dev/null 2>/dev/null; then
    echo ">> Server is up"
    break
  fi
  if ! kill -0 "$SERVER_PID" 2>/dev/null; then
    echo "ERROR: static server exited before becoming ready" >&2
    exit 1
  fi
  sleep 1
  if [[ "$i" == "60" ]]; then
    echo "ERROR: server did not become ready in 60s" >&2
    exit 1
  fi
done

install_vr_deps
run_playwright
[[ "$PUBLISH_BASELINES" == "1" ]] && publish_baselines
echo ">> Done. HTML report: $VR_DIR/playwright-report/index.html"
